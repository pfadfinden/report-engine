package de.pfadfinden.report_engine.preprocessor.Tasks;

import de.pfadfinden.report_engine.preprocessor.AbstractFollowUpTaskCommand;
import de.pfadfinden.report_engine.preprocessor.Metadata.ReportMetadata;
import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import picocli.CommandLine.Command;
import picocli.CommandLine.Option;

/**
 * Generates the public index page of the reports documentation: all reports grouped by {@code
 * category} (thematic overview), each linking to its page generated by {@code
 * generate-md-details-public}. Meant to be written next to those pages, e.g. with {@code
 * --fileName=details-public/index.md}.
 */
@Command(name = "generate-md-overview")
public class GenerateMarkdownOverviewTask extends AbstractFollowUpTaskCommand {

  private static final String EMPTY = "–";

  @Option(
      names = {"--fileName"},
      defaultValue = "overview.md",
      description =
          "store the output in this file (relative to the output dir), including suffix. Links to"
              + " the report pages assume the file is placed in the same directory as those"
              + " (details-public/).")
  private String fileName;

  @Option(
      names = {"--title"},
      defaultValue = "Verfügbare Berichte",
      description = "heading of the page (default: '${DEFAULT-VALUE}')")
  private String title = "Verfügbare Berichte";

  @Option(
      names = {"--category-order"},
      split = ",",
      description =
          "comma separated category names in the order they should appear; remaining categories"
              + " follow alphabetically.")
  private List<String> categoryOrder = List.of();

  @Option(
      names = {"--category-order-file"},
      description =
          "text file with one category name per line, in the order they should appear; added"
              + " before the categories given with --category-order. Useful when names contain"
              + " spaces or other characters that are awkward on the command line.")
  private File categoryOrderFile;

  @Override
  public void export(Stream<ReportMetadata> reports) {
    if (categoryOrderFile != null) {
      try {
        List<String> fromFile =
            Files.readAllLines(categoryOrderFile.toPath(), StandardCharsets.UTF_8).stream()
                .map(String::trim)
                .filter(line -> !line.isEmpty())
                .toList();
        categoryOrder = Stream.concat(fromFile.stream(), categoryOrder.stream()).toList();
      } catch (IOException e) {
        throw new RuntimeException("Failed to read " + categoryOrderFile, e);
      }
    }
    Path target = this.options.outputDir().toPath().resolve(this.fileName);

    try {
      Path parent = target.getParent();
      if (parent != null) {
        Files.createDirectories(parent);
      }
      Files.writeString(target, render(reports.toList()), StandardCharsets.UTF_8);
    } catch (IOException e) {
      throw new RuntimeException("Failed to generate reports overview", e);
    }
  }

  String render(List<ReportMetadata> reports) {
    Map<String, List<ReportMetadata>> byCategory =
        reports.stream()
            .sorted(Comparator.comparing(r -> Objects.toString(r.title, r.id).toLowerCase()))
            .collect(
                Collectors.groupingBy(
                    r ->
                        isBlank(r.category)
                            ? GenerateMarkdownCatalogueTask.UNCATEGORIZED
                            : r.category.trim(),
                    LinkedHashMap::new,
                    Collectors.toList()));

    List<String> categories = new ArrayList<>(byCategory.keySet());
    categories.sort(
        Comparator.comparingInt(this::categoryRank)
            .thenComparing(c -> c.equals(GenerateMarkdownCatalogueTask.UNCATEGORIZED))
            .thenComparing(Comparator.naturalOrder()));

    StringBuilder md = new StringBuilder();
    md.append("# ").append(title).append("\n\n");
    md.append("Alle verfügbaren Berichte, nach Themen geordnet.\n");

    for (String category : categories) {
      md.append("\n## ").append(category).append("\n\n");
      md.append("| Bericht | Beschreibung | Format |\n");
      md.append("|---|---|---|\n");
      byCategory.get(category).forEach(report -> md.append(row(report)).append('\n'));
    }
    return md.toString();
  }

  private int categoryRank(String category) {
    int index = categoryOrder.indexOf(category);
    return index < 0 ? Integer.MAX_VALUE : index;
  }

  private static String row(ReportMetadata report) {
    String formats =
        report.outputFormats == null
            ? ""
            : report.outputFormats.stream()
                .map(String::toUpperCase)
                .collect(Collectors.joining(", "));
    return "| "
        + String.join(
            " | ",
            "[" + cell(report.title) + "](./" + report.id + ".md)",
            cell(report.description),
            cell(formats))
        + " |";
  }

  /** Makes a value safe for a Markdown table cell; empty values render as a dash. */
  private static String cell(String value) {
    if (isBlank(value)) {
      return EMPTY;
    }
    return value.trim().replace("|", "\\|").replace("\r\n", "\n").replace("\n", "<br/>");
  }

  private static boolean isBlank(String value) {
    return value == null || value.isBlank();
  }
}
